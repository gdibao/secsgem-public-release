export type AppSettingRegistryItem = {
  cacheScopes: Array<'app-settings' | 'brand' | 'runtime' | 's3' | 'user-state'>;
  domain: AppSettingDomain;
  key: AppSettingKey;
  publicRuntime: boolean;
  sensitive: boolean;
};

const inferDomain = (key: AppSettingKey): AppSettingDomain => {
  if (key.startsWith('about.')) return 'about';
  if (key.startsWith('brand.') || key.startsWith('sidebar.') || key.startsWith('home.')) {
    return 'brand';
  }
  if (key.startsWith('desktop.')) return 'client';
  if (key.startsWith('composio.')) return 'composio';
  if (
    key.startsWith('community.') ||
    key.startsWith('recommendation.') ||
    key.startsWith('expertPlaza.')
  ) {
    return 'content';
  }
  if (key.startsWith('auth.') || key.startsWith('onboarding.') || key.startsWith('upload.')) {
    return 'growth';
  }
  if (key.startsWith('notification.')) return 'notification';
  if (key.startsWith('moduleApp.')) return 'module-apps';
  if (key.startsWith('payment.')) return 'payments';
  if (
    key.startsWith('model.') ||
    key.startsWith('default') ||
    key.startsWith('memory.') ||
    key.startsWith('vector.')
  ) {
    return 'model';
  }
  if (key.startsWith('pricing.') || key.startsWith('plans.')) return 'pricing';
  if (key.startsWith('storage.')) return 'storage';
  if (key.startsWith('user.') || key.startsWith('profile.')) return 'user-defaults';
  if (key.startsWith('orders.') || key.startsWith('referral.') || key.startsWith('cron.')) {
    return 'operations';
  }
  return 'system';
};

